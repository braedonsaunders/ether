package auth

import "github.com/braedonsaunders/ether/internal/store"

// Membership deactivation is emitted by the database in the same transaction
// as every active-to-inactive transition, including Plex friend sync and
// direct validation. Consumers must install transactional AFTER INSERT triggers;
// event rows are removed only after those triggers return, in the same transaction.
func init() {
	store.Register("auth", 7, `
CREATE TABLE identity_viewer_deactivations (id INTEGER PRIMARY KEY AUTOINCREMENT, viewer_id INTEGER NOT NULL);
CREATE TRIGGER identity_viewer_deactivated AFTER UPDATE OF active ON auth_users
WHEN OLD.active=1 AND NEW.active=0 BEGIN
 INSERT INTO identity_viewer_deactivations(viewer_id) VALUES(NEW.id);
 DELETE FROM identity_viewer_deactivations WHERE id=last_insert_rowid();
END;`)
	store.RegisterDialect("auth", 7, store.Postgres, `
CREATE TABLE identity_viewer_deactivations (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, viewer_id BIGINT NOT NULL);
CREATE FUNCTION identity_emit_viewer_deactivation() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE event_id BIGINT;
BEGIN
 IF OLD.active=1 AND NEW.active=0 THEN
  INSERT INTO identity_viewer_deactivations(viewer_id) VALUES(NEW.id) RETURNING id INTO event_id;
  DELETE FROM identity_viewer_deactivations WHERE id=event_id;
 END IF;
 RETURN NEW;
END;
$$;
CREATE TRIGGER identity_viewer_deactivated AFTER UPDATE OF active ON auth_users FOR EACH ROW EXECUTE FUNCTION identity_emit_viewer_deactivation();`)
}
