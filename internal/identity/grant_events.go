package identity

import "github.com/braedonsaunders/ether/internal/store"

// Grant revocations are emitted within the grant mutation transaction. A
// subscriber can remove only destinations bound to that credential. Subscribers
// must use transactional AFTER INSERT triggers; event rows are transient.
func init() {
	store.Register("identity_grants", 2, `
CREATE TABLE identity_grant_revocations (id INTEGER PRIMARY KEY AUTOINCREMENT, viewer_id INTEGER NOT NULL, grant_hash TEXT NOT NULL);
CREATE TRIGGER identity_grant_revoked AFTER UPDATE OF revoked ON identity_grants
WHEN OLD.revoked=0 AND NEW.revoked=1 BEGIN
 INSERT INTO identity_grant_revocations(viewer_id,grant_hash) VALUES(NEW.viewer_id,NEW.hash);
 DELETE FROM identity_grant_revocations WHERE id=last_insert_rowid();
END;`)
	store.RegisterDialect("identity_grants", 2, store.Postgres, `
CREATE TABLE identity_grant_revocations (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, viewer_id BIGINT NOT NULL, grant_hash TEXT NOT NULL);
CREATE FUNCTION identity_emit_grant_revocation() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE event_id BIGINT;
BEGIN
 IF OLD.revoked=0 AND NEW.revoked=1 THEN
  INSERT INTO identity_grant_revocations(viewer_id,grant_hash) VALUES(NEW.viewer_id,NEW.hash) RETURNING id INTO event_id;
  DELETE FROM identity_grant_revocations WHERE id=event_id;
 END IF;
 RETURN NEW;
END;
$$;
CREATE TRIGGER identity_grant_revoked AFTER UPDATE OF revoked ON identity_grants FOR EACH ROW EXECUTE FUNCTION identity_emit_grant_revocation();`)
}
