package devreference

import (
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// MachineReference renders both agent entry points from the same contract corpus
// and authored topics the console reads. No runtime indexing or generation.
func MachineReference(root string, corpus []byte) (short, full []byte, err error) {
	var sections []Section
	if err = json.Unmarshal(corpus, &sections); err != nil {
		return
	}
	var guides []struct {
		ID    string `json:"id"`
		Title string `json:"title"`
		Body  string `json:"body"`
	}
	var guideJSON []byte
	guideJSON, err = os.ReadFile(filepath.Join(root, "web/src/pages/plugins/reference-guides.json"))
	if err != nil {
		return
	}
	if err = json.Unmarshal(guideJSON, &guides); err != nil {
		return
	}
	var index, all strings.Builder
	intro := "# Ether plugin reference\n\n> Build EPP/1 plugins with the exact shipped manifest, SDK and host-service contracts.\n\nGenerated by go generate ./internal/plugins/devreference. Do not edit generated files.\nDeveloper documentation and API vocabulary are in English. Capabilities describe behavior; permissions grant access. Hosted QuickJS is not Node.\n\n"
	index.WriteString(intro)
	all.WriteString(intro)
	index.WriteString("Full contract: [llms-full.txt](/ether/plugins/reference/llms-full.txt)\n\n## Topics\n\n")
	for _, g := range guides {
		fmt.Fprintf(&index, "- [%s](/ether/plugins/reference/%s)\n", g.Title, g.ID)
		fmt.Fprintf(&all, "## %s\n\n%s\n\n", g.Title, g.Body)
	}
	for _, s := range sections {
		if s.Path == "sdk/AGENTS.md" {
			index.WriteString("\n## Authoring guide\n\n")
			index.WriteString(s.Code)
		}
		fmt.Fprintf(&all, "## Source: %s\n\n", s.Path)
		if strings.HasSuffix(s.Path, ".md") {
			all.WriteString(s.Code)
		} else {
			// A longer fence keeps embedded Markdown examples intact.
			all.WriteString("``````\n" + s.Code + "\n``````")
		}
		all.WriteString("\n\n")
	}
	return []byte(index.String()), []byte(all.String()), nil
}
