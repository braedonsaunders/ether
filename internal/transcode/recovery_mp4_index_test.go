type recoveryMemorySource struct {
	core.EncoderInputLease
	data                              []byte
	revision                          string
	size                              int64
	reads, total, maxRead, identities int
	read                              func(context.Context, []byte, int64) (int, error)
	identity                          func(int) (string, int64, error)
}

func (s *recoveryMemorySource) RecoverySourceIdentity() (string, int64, error) {
	s.identities++
	if s.identity != nil {
		return s.identity(s.identities)
	}
	return s.revision, s.size, nil
}
func (s *recoveryMemorySource) ReadRecoveryAt(ctx context.Context, revision string, p []byte, off int64) (int, error) {
	s.reads++
	s.total += len(p)
	s.maxRead = max(s.maxRead, len(p))
	if revision != s.revision {
		return 0, errors.New("revision")
	}
	if s.read != nil {
		return s.read(ctx, p, off)
	}
	if ctx.Err() != nil {
		return 0, ctx.Err()
	}
	return bytes.NewReader(s.data).ReadAt(p, off)
}
func recoveryIndexFixture(t *testing.T) (*recoveryMemorySource, *core.RecoveryAACCursor) {
	t.Helper()
	data, err := os.ReadFile("testdata/recovery_source_aac.m4a")
	if err != nil {
		t.Fatal(err)
	}
	// Generated by recovery_clock_lab.py: 8s/48kHz chirp+impulses, native AAC96k.
	// Digests independently extracted from actual retained TS ADTS payloads in
	// copy-continuous/00078.ts (last AU) and copy-cold/00077.ts (first AU).
	digest := func(raw string) [32]byte {
		b, e := hex.DecodeString(raw)
		if e != nil || len(b) != 32 {
			t.Fatal("bad digest")
		}
		return [32]byte(b)
	}
	a := &core.RecoveryAACCursor{SourceRevision: "generated-immutable", StreamIndex: 0, SampleRate: 48000, Channels: 1, SamplesPerAU: 1024, NextSample: 184320, SourceNext: core.RecoveryPacketClock{PTS: 184320, DTS: 184320, TimeBaseNum: 1, TimeBaseDen: 48000}, PreviousRawAUSHA256: digest("90e80460bb56a14b1ad140213ffec5888e11987fad4417be20523c72ab00feac"), NextRawAUSHA256: digest("edf5d340bc8e50b2a7f3c2f78379042c51da66b1c1b1221ff4d2d9d4098cddc6"), CodecConfigSHA256: digest("cc03fc678ee0f27c779bd58ce6d310cc6c441436b52bd1c9cacc1494a26d8beb")}
	return &recoveryMemorySource{data: data, revision: a.SourceRevision, size: int64(len(data))}, a
}
func recoveryBoxPayload(t *testing.T, b []byte, name string) []byte {
	t.Helper()
	i := bytes.Index(b, []byte(name))
	if i < 4 {
		t.Fatalf("missing box %s", name)
	}
	size := int(binary.BigEndian.Uint32(b[i-4:]))
	return b[i+4 : i-4+size]
}

func TestRecoveryAACIndexActualNeighborPayloads(t *testing.T) {
	src, want := recoveryIndexFixture(t)
	facts, err := verifyRecoveryAACIndex(t.Context(), src, want)
	if err != nil {
		t.Fatal(err)
	}
	if !facts.DecoderRollSignaled || facts.DecoderRollDistance != -1 || facts.NextSample != want.NextSample || facts.SourceNext != want.SourceNext || facts.PreviousRawAUSHA256 != want.PreviousRawAUSHA256 || facts.NextRawAUSHA256 != want.NextRawAUSHA256 || facts.CodecConfigSHA256 != want.CodecConfigSHA256 || facts.PreviousOffset+int64(facts.PreviousSize) != facts.NextOffset {
		t.Fatalf("wrong actual index facts: %+v", facts)
	}
	if src.maxRead > 64<<10 || src.total > recoveryIndexReadBudget || src.identities != 2 {
		t.Fatalf("read accounting %+v", src)
	}
}
func TestRecoveryAACIndexRejectsAmbiguousMetadata(t *testing.T) {
	cases := map[string]func(*recoveryMemorySource, *core.RecoveryAACCursor){
		"wrong-revision":     func(s *recoveryMemorySource, a *core.RecoveryAACCursor) { a.SourceRevision = "other" },
		"wrong-predecessor":  func(s *recoveryMemorySource, a *core.RecoveryAACCursor) { a.PreviousRawAUSHA256[0]++ },
		"wrong-next":         func(s *recoveryMemorySource, a *core.RecoveryAACCursor) { a.NextRawAUSHA256[0]++ },
		"wrong-config":       func(s *recoveryMemorySource, a *core.RecoveryAACCursor) { a.CodecConfigSHA256[0]++ },
		"wrong-source-clock": func(s *recoveryMemorySource, a *core.RecoveryAACCursor) { a.SourceNext.PTS++ },
		"wrong-channel":      func(s *recoveryMemorySource, a *core.RecoveryAACCursor) { a.Channels = 2 },
		"wrong-track":        func(s *recoveryMemorySource, a *core.RecoveryAACCursor) { a.StreamIndex = 1 },
		"partial-sample":     func(s *recoveryMemorySource, a *core.RecoveryAACCursor) { a.NextSample++ },
		"short-source":       func(s *recoveryMemorySource, a *core.RecoveryAACCursor) { s.size-- },
		"variable-delta": func(s *recoveryMemorySource, a *core.RecoveryAACCursor) {
			b := recoveryBoxPayload(t, s.data, "stts")
			binary.BigEndian.PutUint32(b[12:], 960)
		},
		"huge-table-count": func(s *recoveryMemorySource, a *core.RecoveryAACCursor) {
			b := recoveryBoxPayload(t, s.data, "stsz")
			binary.BigEndian.PutUint32(b[8:], 0xffffffff)
		},
		"payload-outside-mdat": func(s *recoveryMemorySource, a *core.RecoveryAACCursor) {
			b := recoveryBoxPayload(t, s.data, "stco")
			binary.BigEndian.PutUint32(b[8:], 0)
		},
		"oversize-au": func(s *recoveryMemorySource, a *core.RecoveryAACCursor) {
			b := recoveryBoxPayload(t, s.data, "stsz")
			binary.BigEndian.PutUint32(b[12:], 8192)
		},
		"sample-description-switch": func(s *recoveryMemorySource, a *core.RecoveryAACCursor) {
			b := recoveryBoxPayload(t, s.data, "stsc")
			binary.BigEndian.PutUint32(b[16:], 2)
		},
		"empty-edit": func(s *recoveryMemorySource, a *core.RecoveryAACCursor) {
			b := recoveryBoxPayload(t, s.data, "elst")
			binary.BigEndian.PutUint32(b[12:], 0xffffffff)
		},
		"non-unit-edit": func(s *recoveryMemorySource, a *core.RecoveryAACCursor) {
			b := recoveryBoxPayload(t, s.data, "elst")
			binary.BigEndian.PutUint32(b[16:], 0x20000)
		},
		"wrong-roll": func(s *recoveryMemorySource, a *core.RecoveryAACCursor) {
			b := recoveryBoxPayload(t, s.data, "sgpd")
			b[len(b)-1] = 0xfe
		},
		"sbr": func(s *recoveryMemorySource, a *core.RecoveryAACCursor) {
			i := bytes.Index(s.data, []byte{0x11, 0x88, 0x56, 0xe5, 0})
			if i < 0 {
				t.Fatal("no ASC")
			}
			s.data[i+4] = 0x80
		},
		"short-read": func(s *recoveryMemorySource, a *core.RecoveryAACCursor) {
			s.read = func(context.Context, []byte, int64) (int, error) { return 1, nil }
		},
		"identity-changed": func(s *recoveryMemorySource, a *core.RecoveryAACCursor) {
			s.identity = func(n int) (string, int64, error) {
				if n > 1 {
					return "new", s.size, nil
				}
				return s.revision, s.size, nil
			}
		},
	}
	for name, mutate := range cases {
		t.Run(name, func(t *testing.T) {
			s, a := recoveryIndexFixture(t)
			mutate(s, a)
			if _, err := verifyRecoveryAACIndex(t.Context(), s, a); err == nil {
				t.Fatal("unverified index accepted")
			}
		})
	}
}

func TestRecoveryAACIndexRejectsMalformedDescriptorLength(t *testing.T) {
	src, want := recoveryIndexFixture(t)
	esds := recoveryBoxPayload(t, src.data, "esds")
	if !bytes.Equal(esds[4:9], []byte{0x03, 0x80, 0x80, 0x80, 0x25}) {
		t.Fatal("unexpected fixture ES descriptor")
	}
	// Preserve all seven-bit length payloads and the ASC bytes, but illegally
	// require a fifth length byte. Ordinary probing previously accepted this.
	esds[8] = 0xa5
	if _, err := verifyRecoveryAACIndex(t.Context(), src, want); err == nil {
		t.Fatal("unterminated four-byte descriptor length accepted")
	}
}
func TestRecoveryAACIndexChunkBudget(t *testing.T) {
	src, want := recoveryIndexFixture(t)
	// Large metadata payload is read in bounded chunks; it deliberately has no
	// valid track, so parsing must reject it without reading unrelated payloads.
	size := (128 << 10) + 8
	b := make([]byte, size+8)
	binary.BigEndian.PutUint32(b, uint32(size))
	copy(b[4:], "moov")
	binary.BigEndian.PutUint32(b[8:], uint32(size-8))
	copy(b[12:], "free")
	binary.BigEndian.PutUint32(b[size:], 8)
	copy(b[size+4:], "mdat")
	src.data, src.size = b, int64(len(b))
	if _, err := verifyRecoveryAACIndex(t.Context(), src, want); err == nil || src.maxRead > 64<<10 || src.maxRead != 64<<10 || src.total > recoveryIndexReadBudget {
		t.Fatalf("chunk bound: err=%v max=%d total=%d", err, src.maxRead, src.total)
	}
}
func TestRecoveryAACIndexCancellationJoinsActualRead(t *testing.T) {
	src, want := recoveryIndexFixture(t)
	entered, release := make(chan struct{}), make(chan struct{})
	src.read = func(_ context.Context, p []byte, off int64) (int, error) {
		close(entered)
		<-release
		return bytes.NewReader(src.data).ReadAt(p, off)
	}
	ctx, cancel := context.WithCancel(t.Context())
	defer cancel()
	done := make(chan error, 1)
	go func() { _, err := verifyRecoveryAACIndex(ctx, src, want); done <- err }()
	<-entered
	cancel()
	select {
	case <-done:
		t.Fatal("timeout substituted for actual read completion")
	default:
	}
	close(release)
	if err := <-done; !errors.Is(err, context.Canceled) {
		t.Fatalf("got %v", err)
	}
}

func TestRecoveryAACIndexMetadataBounds(t *testing.T) {
	t.Run("box-count", func(t *testing.T) {
		src, want := recoveryIndexFixture(t)
		b := make([]byte, (recoveryIndexBoxLimit+1)*8)
		for i := 0; i < len(b); i += 8 {
			binary.BigEndian.PutUint32(b[i:], 8)
			copy(b[i+4:], "free")
		}
		src.data, src.size = b, int64(len(b))
		if _, err := verifyRecoveryAACIndex(t.Context(), src, want); err == nil || src.reads > recoveryIndexBoxLimit {
			t.Fatalf("unbounded top boxes: %v reads=%d", err, src.reads)
		}
	})
	t.Run("moov-allocation", func(t *testing.T) {
		src, want := recoveryIndexFixture(t)
		header := make([]byte, 16)
		binary.BigEndian.PutUint32(header, uint32(recoveryMoovLimit+1))
		copy(header[4:], "moov")
		src.data, src.size = header, recoveryMoovLimit+1
		if _, err := verifyRecoveryAACIndex(t.Context(), src, want); err == nil || src.reads != 1 || src.total != 16 {
			t.Fatalf("oversized moov read: %v reads=%d bytes=%d", err, src.reads, src.total)
		}
	})
	t.Run("identity-before-read", func(t *testing.T) {
		src, want := recoveryIndexFixture(t)
		want.SourceRevision = "other"
		if _, err := verifyRecoveryAACIndex(t.Context(), src, want); err == nil || src.reads != 0 {
			t.Fatal("unbound source bytes read")
		}
	})
}

func TestRecoveryAACIndexCo64AndOverflow(t *testing.T) {
	src, want := recoveryIndexFixture(t)
	pos := bytes.Index(src.data, []byte("stco"))
	if pos < 4 {
		t.Fatal("no stco")
	}
	// Promote the generated fixture's single 32-bit chunk offset to co64. The
	// metadata is after mdat, so payload addresses stay unchanged.
	entry := pos + 12
	data := append([]byte(nil), src.data[:entry]...)
	data = append(data, 0, 0, 0, 0)
	data = append(data, src.data[entry:]...)
	for _, name := range []string{"moov", "trak", "mdia", "minf", "stbl", "stco"} {
		i := bytes.Index(data, []byte(name))
		if i < 4 {
			t.Fatal("missing ancestor", name)
		}
		binary.BigEndian.PutUint32(data[i-4:], binary.BigEndian.Uint32(data[i-4:])+4)
	}
	copy(data[pos:], "co64")
	src.data, src.size = data, int64(len(data))
	if _, err := verifyRecoveryAACIndex(t.Context(), src, want); err != nil {
		t.Fatal(err)
	}
	binary.BigEndian.PutUint64(src.data[entry:], uint64(1)<<63)
	if _, err := verifyRecoveryAACIndex(t.Context(), src, want); err == nil {
		t.Fatal("co64 signed overflow accepted")
	}
}
