package main

import (
	"net/http"
	"regexp"
	"strings"
)

// Only the random stream grant query parameter is normalized. Its name and
// surrounding URL bytes remain visible; all other response bytes are compared.
var streamGrant = regexp.MustCompile(`(X-Ether-Stream-Token=)[A-Za-z0-9_-]+`)
var delegationXML = regexp.MustCompile(`(token=")[^"]*(")`)
var delegationJSON = regexp.MustCompile(`("token"\s*:\s*")[^"]*(")`)

func normalizeResponse(body []byte) []byte {
	return streamGrant.ReplaceAll(body, []byte(`${1}<STREAM-TOKEN>`))
}

// Images and media segments are binary payloads and must be compared exactly.
func normalizeCaptureBody(c capture) []byte {
	if c.path == "/security/token" {
		body := delegationXML.ReplaceAll(c.response.Body, []byte(`${1}<DELEGATION-TOKEN>${2}`))
		return delegationJSON.ReplaceAll(body, []byte(`${1}<DELEGATION-TOKEN>${2}`))
	}
	contentType := c.response.Headers.Get("Content-Type")
	if strings.HasPrefix(c.path, "image:") || strings.HasPrefix(c.path, "playback:segment:") || c.path == "subtitle:stream" || c.path == "subtitle:transcode" || strings.HasPrefix(contentType, "image/") || strings.HasPrefix(contentType, "video/") || strings.HasPrefix(contentType, "audio/") || contentType == "application/octet-stream" {
		return c.response.Body
	}
	return normalizeResponse(c.response.Body)
}

// Date is generated by the HTTP server from the wall clock. Every other
// response header is compared, including content and cache headers.
func normalizeHeaders(h http.Header) http.Header {
	out := h.Clone()
	out.Del("Date")
	for key, values := range out {
		for i, v := range values {
			values[i] = string(normalizeResponse([]byte(v)))
		}
		out[key] = values
	}
	return out
}

// Segment files are created at encoder wall time; Last-Modified on those
// ephemeral bytes is a volatile filesystem timestamp, not media metadata.
func normalizeCaptureHeaders(c capture) http.Header {
	h := normalizeHeaders(c.response.Headers)
	// Sec-WebSocket-Accept is the per-connection handshake token derived from
	// the client's random challenge; compare every other handshake header.
	if strings.HasPrefix(c.path, "/:/websocket") && h.Get("Sec-WebSocket-Accept") != "" {
		h.Set("Sec-WebSocket-Accept", "<WEBSOCKET-HANDSHAKE-TOKEN>")
	}
	if strings.HasPrefix(c.path, "playback:segment:") || c.path == "playback:dash:header" || c.path == "playback:dash:0.m4s" || c.path == "livetv:program-segment" || (strings.HasPrefix(c.path, "iptv:") && strings.HasSuffix(c.path, ":relay:media")) || c.path == "iptv:dash:part" {
		h.Del("Last-Modified")
	}
	return h
}
